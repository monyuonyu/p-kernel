/*
 * MainActivity.kt — the FRIENDLY surface (3-layer app-polish wave).
 *
 * Layer 1 (this screen's primary view): a StarfieldView backdrop, the project
 * name, the localized tagline (manifesto line 3), the star's state in human
 * words (shining / asleep), one hero button (灯す / 眠らせる), and Open galaxy.
 * NO raw kernel log inline, NO jargon.
 *
 * Layer 2 (collapsed "Advanced — join a fleet"): a battery-safe toggle bound
 * to PKernelService.PREF_CHARGE_ONLY, the opt-in relay host/port/key fields
 * (Intent extras to PKernelService UNCHANGED), and the door to the engineer
 * page.
 *
 * Layer 3 (LogActivity): the raw stdout tail + node internals + module
 * versions — deliberately technical, reached only from layer 2.
 *
 * All visible strings come from values-<locale>/strings.xml (generated by
 * tools/android/gen_strings.py for the manifesto languages), so the screen
 * speaks the user's language from the first frame, falling back to English.
 */

package io.pkernel

import android.app.NotificationChannel
import android.app.NotificationManager
import android.content.Intent
import android.os.Build
import android.os.Bundle
import android.view.View
import android.widget.Button
import android.widget.EditText
import android.widget.LinearLayout
import android.widget.SeekBar
import android.widget.TextView
import androidx.appcompat.app.AppCompatActivity
import androidx.appcompat.widget.SwitchCompat

class MainActivity : AppCompatActivity() {

    private lateinit var nodeIdField: EditText
    private lateinit var relayHostField: EditText
    private lateinit var relayPortField: EditText
    private lateinit var relayKeyField: EditText
    private lateinit var advancedGroup: LinearLayout
    private lateinit var batterySafeSwitch: SwitchCompat
    private lateinit var floorLabel: TextView
    private lateinit var floorSeek: SeekBar
    private lateinit var wifiOnlySwitch: SwitchCompat
    private lateinit var startOnBootSwitch: SwitchCompat

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        ensureNotificationChannel()

        /* UX constitution (docs/product-soul.md): users don't care about
         * kernels. The DEFAULT path has no form — the node lights itself and
         * the first thing a person sees is the galaxy's own introduction (the
         * manifesto gate). This settings screen survives ONLY as the
         * "advanced" screen, reached from the ⋮ corner of the galaxy. */
        if (!intent.getBooleanExtra(EXTRA_ADVANCED, false)) {
            val prefs = getSharedPreferences(PREFS, MODE_PRIVATE)
            if (!prefs.contains(PREF_NODE_ID))   // first light: mint a random id
                prefs.edit().putInt(PREF_NODE_ID, 2 + (Math.random() * 60).toInt()).apply()
            val nodeId = prefs.getInt(PREF_NODE_ID, 1)
            startKernelWith(
                nodeId,
                prefs.getString(PREF_RELAY_HOST, "") ?: "",
                prefs.getInt(PREF_RELAY_PORT, 7400),
                prefs.getString(PREF_RELAY_KEY, "") ?: "")
            startActivity(Intent(this, GalaxyActivity::class.java).apply {
                putExtra(GalaxyActivity.EXTRA_NODE_ID, nodeId)
            })
            finish()
            return
        }

        setContentView(R.layout.activity_main)

        nodeIdField    = findViewById(R.id.field_node_id)
        relayHostField = findViewById(R.id.field_relay_host)
        relayPortField = findViewById(R.id.field_relay_port)
        relayKeyField  = findViewById(R.id.field_relay_key)
        advancedGroup  = findViewById(R.id.advanced_group)
        batterySafeSwitch = findViewById(R.id.switch_battery_safe)
        floorLabel        = findViewById(R.id.label_battery_floor)
        floorSeek         = findViewById(R.id.seek_battery_floor)
        wifiOnlySwitch    = findViewById(R.id.switch_wifi_only)
        startOnBootSwitch = findViewById(R.id.switch_start_on_boot)

        /* prefill from the persisted settings (the auto path uses the same);
         * first run mints a RANDOM node id instead of everyone being "1"
         * (honest bound: ids live in 0..63 — true uniqueness needs a
         * key-derived id, a named future wave). */
        val prefs = getSharedPreferences(PREFS, MODE_PRIVATE)
        if (!prefs.contains(PREF_NODE_ID))
            prefs.edit().putInt(PREF_NODE_ID, 2 + (Math.random() * 60).toInt()).apply()
        nodeIdField.setText(prefs.getInt(PREF_NODE_ID, 1).toString())
        relayHostField.setText(prefs.getString(PREF_RELAY_HOST, "") ?: "")
        relayPortField.setText(prefs.getInt(PREF_RELAY_PORT, 7400).toString())
        relayKeyField.setText(prefs.getString(PREF_RELAY_KEY, "") ?: "")

        /* Battery-safe toggle: bound to PKernelService.PREF_CHARGE_ONLY in the
         * "ump" prefs (default ON). Toggling persists; it takes effect at the
         * next gate check (powerAllowed()) — we do NOT touch the gate logic. */
        batterySafeSwitch.isChecked =
            prefs.getBoolean(PKernelService.PREF_CHARGE_ONLY, true)
        batterySafeSwitch.setOnCheckedChangeListener { _, checked ->
            getSharedPreferences(PREFS, MODE_PRIVATE).edit()
                .putBoolean(PKernelService.PREF_CHARGE_ONLY, checked).apply()
        }

        /* Battery floor SeekBar: range 10..50 step 5 (9 stops => max=8).
         * progress p maps to floor = FLOOR_MIN + p*FLOOR_STEP. The label shows
         * the live value; PREF_BATTERY_FLOOR is what powerAllowed() reads. The
         * pref persists; it takes effect at the next gate check — we do NOT
         * touch the pause/resume/JobScheduler logic, only the threshold value. */
        val savedFloor = prefs.getInt(PKernelService.PREF_BATTERY_FLOOR,
                                      PKernelService.BATTERY_FLOOR_PCT)
                             .coerceIn(FLOOR_MIN, FLOOR_MAX)
        floorSeek.progress = (savedFloor - FLOOR_MIN) / FLOOR_STEP
        floorLabel.text = getString(R.string.pref_floor_label, savedFloor)
        floorSeek.setOnSeekBarChangeListener(object : SeekBar.OnSeekBarChangeListener {
            override fun onProgressChanged(sb: SeekBar?, progress: Int, fromUser: Boolean) {
                val floor = FLOOR_MIN + progress * FLOOR_STEP
                floorLabel.text = getString(R.string.pref_floor_label, floor)
                getSharedPreferences(PREFS, MODE_PRIVATE).edit()
                    .putInt(PKernelService.PREF_BATTERY_FLOOR, floor).apply()
            }
            override fun onStartTrackingTouch(sb: SeekBar?) {}
            override fun onStopTrackingTouch(sb: SeekBar?) {}
        })

        /* WiFi-only toggle: PREF_WIFI_ONLY (default OFF). Takes effect at the
         * next gate check (runAllowed()); the service's NetworkCallback then
         * pauses/resumes the node as connectivity changes. */
        wifiOnlySwitch.isChecked = prefs.getBoolean(PKernelService.PREF_WIFI_ONLY, false)
        wifiOnlySwitch.setOnCheckedChangeListener { _, checked ->
            getSharedPreferences(PREFS, MODE_PRIVATE).edit()
                .putBoolean(PKernelService.PREF_WIFI_ONLY, checked).apply()
        }

        /* Start-on-boot toggle: PREF_START_ON_BOOT (default OFF). Read by
         * BootReceiver on ACTION_BOOT_COMPLETED. */
        startOnBootSwitch.isChecked =
            prefs.getBoolean(PKernelService.PREF_START_ON_BOOT, false)
        startOnBootSwitch.setOnCheckedChangeListener { _, checked ->
            getSharedPreferences(PREFS, MODE_PRIVATE).edit()
                .putBoolean(PKernelService.PREF_START_ON_BOOT, checked).apply()
        }

        findViewById<Button>(R.id.btn_start ).setOnClickListener { startKernel() }
        findViewById<Button>(R.id.btn_stop  ).setOnClickListener { stopKernel()  }
        findViewById<Button>(R.id.btn_galaxy).setOnClickListener { openGalaxy()  }
        findViewById<Button>(R.id.btn_engineer).setOnClickListener {
            startActivity(Intent(this, LogActivity::class.java))
        }
        findViewById<Button>(R.id.btn_reintro).setOnClickListener { replayIntro() }

        /* state, in human words: poll the star's window; swap 灯す/眠らせる
         * so the screen never asks you to light an already-shining star. */
        Thread({
            while (!isFinishing) {
                val id = nodeIdField.text.toString().toIntOrNull() ?: 1
                val lit = try {
                    java.net.Socket().use { sk ->
                        sk.connect(java.net.InetSocketAddress("127.0.0.1", 7800 + id - 1), 300); true }
                } catch (_: Throwable) { false }
                runOnUiThread {
                    findViewById<TextView>(R.id.star_status).text =
                        getString(if (lit) R.string.star_lit else R.string.star_dark)
                    findViewById<Button>(R.id.btn_start).visibility =
                        if (lit) View.GONE else View.VISIBLE
                    findViewById<Button>(R.id.btn_stop).visibility =
                        if (lit) View.VISIBLE else View.GONE
                }
                try { Thread.sleep(1200) } catch (_: InterruptedException) { return@Thread }
            }
        }, "star-status").apply { isDaemon = true; start() }

        /* "Advanced — join a fleet": reveal the settings group on tap. Solo is
         * the default; the relay (and the engineer page) are opt-in. */
        findViewById<TextView>(R.id.advanced_toggle).setOnClickListener {
            advancedGroup.visibility =
                if (advancedGroup.visibility == View.VISIBLE) View.GONE else View.VISIBLE
        }
    }

    private fun startKernel() {
        val nodeId = nodeIdField.text.toString().toIntOrNull() ?: 1
        val host   = relayHostField.text.toString().trim()
        val port   = relayPortField.text.toString().toIntOrNull() ?: 7400
        val key    = relayKeyField.text.toString().trim()
        /* advanced-screen settings persist so the no-form default path
         * relights the same star next launch. */
        getSharedPreferences(PREFS, MODE_PRIVATE).edit()
            .putInt(PREF_NODE_ID, nodeId).putString(PREF_RELAY_HOST, host)
            .putInt(PREF_RELAY_PORT, port).putString(PREF_RELAY_KEY, key)
            .apply()
        startKernelWith(nodeId, host, port, key)
    }

    private fun startKernelWith(nodeId: Int, host: String, port: Int, key: String) {
        val intent = Intent(this, PKernelService::class.java).apply {
            putExtra(PKernelService.EXTRA_NODE_ID,    nodeId)
            putExtra(PKernelService.EXTRA_RELAY_HOST, host)
            putExtra(PKernelService.EXTRA_RELAY_PORT, port)
            putExtra(PKernelService.EXTRA_RELAY_KEY,  key)
        }
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            startForegroundService(intent)
        } else {
            startService(intent)
        }
    }

    private fun stopKernel() {
        stopService(Intent(this, PKernelService::class.java))
    }

    /* galaxy.md D4: open the observation window. The galaxy port follows the
     * node id (7800 + node_id - 1), so pass the same id the service booted. */
    private fun openGalaxy() {
        val nodeId = nodeIdField.text.toString().toIntOrNull() ?: 1
        startActivity(Intent(this, GalaxyActivity::class.java).apply {
            putExtra(GalaxyActivity.EXTRA_NODE_ID, nodeId)
        })
    }

    /* "View introduction again": open the galaxy and replay the picture-book
     * intro (pictures only, no re-consent — EXTRA_SHOW_INTRO -> ?intro=1 ->
     * introOpen(false) in galaxy.html). For a returning, already-consented
     * user who wants to re-read the welcome. */
    private fun replayIntro() {
        val nodeId = nodeIdField.text.toString().toIntOrNull() ?: 1
        startActivity(Intent(this, GalaxyActivity::class.java).apply {
            putExtra(GalaxyActivity.EXTRA_NODE_ID, nodeId)
            putExtra(GalaxyActivity.EXTRA_SHOW_INTRO, true)
        })
    }

    companion object {
        const val EXTRA_ADVANCED = "advanced"
        private const val PREFS = "ump"
        // Battery-floor SeekBar range (10..50, step 5 -> 9 stops, SeekBar max=8).
        private const val FLOOR_MIN = 10
        private const val FLOOR_MAX = 50
        private const val FLOOR_STEP = 5
        private const val PREF_NODE_ID = "node_id"
        private const val PREF_RELAY_HOST = "relay_host"
        private const val PREF_RELAY_PORT = "relay_port"
        private const val PREF_RELAY_KEY = "relay_key"
    }

    private fun ensureNotificationChannel() {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            val nm = getSystemService(NotificationManager::class.java)
            val ch = NotificationChannel(
                PKernelService.CHANNEL_ID,
                getString(R.string.notif_channel_name),
                NotificationManager.IMPORTANCE_LOW
            ).apply {
                description = getString(R.string.notif_channel_desc)
                setShowBadge(false)
            }
            nm?.createNotificationChannel(ch)
        }
    }
}
