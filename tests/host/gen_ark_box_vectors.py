#!/usr/bin/env python3
"""gen_ark_box_vectors.py -> C header on stdout (tests/host/ark_box_vectors.h).

K4 of the key box (ark-entry.md 3b): the wrap of a fixed record key for a fixed recipient
with a fixed ephemeral key, and a record sealed with that key, computed with python's
cryptography (OpenSSL's X25519, HKDF and ChaCha20-Poly1305), not with ark_crypto.c.
The fixed inputs are SHA-512 of short labels (first 32 bytes). An auditor reruns this
and diffs the header."""
import hashlib
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives import hashes, serialization

def fixed(label):
    return hashlib.sha512(label.encode()).digest()[:32]

def pub(priv):
    return X25519PrivateKey.from_private_bytes(priv).public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw)

RK = fixed("p-kernel ark box test: record key")
R = fixed("p-kernel ark box test: recipient")
E = fixed("p-kernel ark box test: ephemeral")
INFO = b"p-kernel ark wrap v1"
rpub, epub = pub(R), pub(E)
K = X25519PrivateKey.from_private_bytes(E).exchange(X25519PublicKey.from_public_bytes(rpub))
wk = HKDF(algorithm=hashes.SHA512(), length=32, salt=epub + rpub, info=INFO).derive(K)
wrapped = epub + ChaCha20Poly1305(wk).encrypt(bytes(12), RK, None)
assert len(wrapped) == 80
PT = "A record, kept as it was written. 書いたままの記録。".encode()
AAD = b"self/rec v1"
sealed = ChaCha20Poly1305(RK).encrypt(bytes(12), PT, AAD)

def arr(name, b):
    s = ", ".join("0x%02x" % x for x in b)
    out, line = [], ""
    for tok in s.split(", "):
        if len(line) + len(tok) > 90:
            out.append(line); line = ""
        line += tok + ", "
    out.append(line)
    return "static const uint8_t %s[%d] = {\n    %s\n};" % (name, len(b), "\n    ".join(l.rstrip() for l in out))

print("/* generated by tests/host/gen_ark_box_vectors.py (python cryptography). Do not edit. */")
print("#include <stdint.h>")
print("#define BOX_INFO \"%s\"" % INFO.decode())
for n, b in (("BOX_RK", RK), ("BOX_R", R), ("BOX_RPUB", rpub), ("BOX_E", E), ("BOX_WRAPPED", wrapped),
             ("BOX_PT", PT), ("BOX_AAD", AAD), ("BOX_CT", sealed[:-16]), ("BOX_TAG", sealed[-16:])):
    print(arr(n, b))
