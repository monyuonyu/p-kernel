#!/usr/bin/env python3
"""gen_ark_hkdf_vectors.py <hkdf_sha512_test.json> -> C header on stdout (tests/host/ark_hkdf_vectors.h).

The HKDF-SHA-512 vectors of Project Wycheproof (C2SP/wycheproof, testvectors_v1/
hkdf_sha512_test.json, Apache-2.0). RFC 5869 has vectors for SHA-256 and SHA-1 only.
Every test is taken: the valid ones with their OKM, the invalid ones (an output longer
than 255 * 64 bytes) to be refused. An OKM longer than 256 bytes is stored as its first
and last 64 bytes and its SHA-512 (computed here with hashlib; the C side's SHA-512 is
pinned by RFC 4231 and the Ed25519 KAT). An auditor fetches the JSON again, checks the
sha256 printed in the header, reruns this and diffs the header."""
import hashlib, json, sys

raw = open(sys.argv[1], "rb").read()
d = json.loads(raw)
assert d["algorithm"] == "HKDF-SHA-512", d["algorithm"]
tests = [t for g in d["testGroups"] for t in g["tests"]]
assert len(tests) == d["numberOfTests"], (len(tests), d["numberOfTests"])

def arr(name, b):
    if not b:
        return "static const uint8_t %s[1] = {0};  /* empty */\n" % name
    s = ", ".join("0x%02x" % x for x in b)
    out, line = [], ""
    for tok in s.split(", "):
        if len(line) + len(tok) > 90:
            out.append(line); line = ""
        line += tok + ", "
    out.append(line)
    return "static const uint8_t %s[%d] = {\n    %s\n};\n" % (name, len(b), "\n    ".join(l.rstrip() for l in out))

print("/* generated by tests/host/gen_ark_hkdf_vectors.py from Wycheproof hkdf_sha512_test.json")
print(" * (sha256 %s, %d tests). Do not edit. */" % (hashlib.sha256(raw).hexdigest(), len(tests)))
print("#include <stdint.h>\n#include <stddef.h>")
rows = []
nvalid = ninvalid = 0
for t in tests:
    i = t["tcId"]
    ikm, salt, info = (bytes.fromhex(t[k]) for k in ("ikm", "salt", "info"))
    size = t["size"]
    assert t["result"] in ("valid", "invalid"), t
    print(arr("HK_IKM_%d" % i, ikm), end="")
    print(arr("HK_SALT_%d" % i, salt), end="")
    print(arr("HK_INFO_%d" % i, info), end="")
    if t["result"] == "valid":
        nvalid += 1
        okm = bytes.fromhex(t["okm"])
        assert len(okm) == size, (i, len(okm), size)
        big = size > 256
        print(arr("HK_OKM_%d" % i, okm[:64] + okm[-64:] if big else okm), end="")
        if big:
            print(arr("HK_OKM_SHA_%d" % i, hashlib.sha512(okm).digest()), end="")
        rows.append("    { %d, 1, %d, HK_IKM_%d, %d, HK_SALT_%d, %d, HK_INFO_%d, %d, HK_OKM_%d, %s },"
                    % (i, size, i, len(ikm), i, len(salt), i, len(info), i, "HK_OKM_SHA_%d" % i if big else "NULL"))
    else:
        ninvalid += 1
        assert "SizeTooLarge" in t["flags"] and size > 255 * 64, t
        rows.append("    { %d, 0, %d, HK_IKM_%d, %d, HK_SALT_%d, %d, HK_INFO_%d, %d, NULL, NULL },"
                    % (i, size, i, len(ikm), i, len(salt), i, len(info)))
print("struct hk_vec { int id, valid; size_t size; const uint8_t *ikm; size_t ikm_len;")
print("                const uint8_t *salt; size_t salt_len; const uint8_t *info; size_t info_len;")
print("                const uint8_t *okm; const uint8_t *okm_sha; };")
print("/* okm: the whole OKM, or (okm_sha != NULL) its first and last 64 bytes */")
print("static const struct hk_vec HK[%d] = {" % len(rows))
print("\n".join(rows))
print("};")
print("#define HK_VALID %d\n#define HK_INVALID %d" % (nvalid, ninvalid))
