#!/bin/bash
# ---------------------------------------------------------------------------
# run_restore.sh - [dmn-restore] B4 remainder (research/b4-step3-result.md, the
# last section): the DMN reads the saved best back when live drifts past it by
# more than ST_DMN_RESTORE_MARGIN and the saved one is better than live now.
#   plain build: must PASS.
#   FALSIFIERS: -DST_DMN_RESTORE_DISABLE must FAIL ([restore-back] RED),
#               -DST_DMN_REST_DISABLE must FAIL ([restore-rest] RED),
#               -DST_DMN_REST_ABORT_KEEP must FAIL ([restore-rest] writer RED),
#               -DST_DMN_REST_DLB_KEEP must FAIL ([restore-rest] DLB winner RED),
#               -DDLB_NO_REFUND must FAIL ([restore-dlb] RED, run "dlb"),
#               -DDLB_NO_EVICT_KEPT must FAIL ([restore-dlb] full ring RED, run "dlb"),
#               -DDLB_REFUND_UNBOUNDED must FAIL ([restore-dlb] once RED, run "dlb").
# ---------------------------------------------------------------------------
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
CC="${CC:-cc}"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
L="$ROOT/arch/common/llm"
SRC="$HERE/student_restore_test.c $L/student.c $L/cradle.c $L/dlb.c $L/held_indep.c"
STUB="$WORK/stub.c"
printf '%s\n' \
  '/* auto-generated by run_restore.sh: link-only stubs (chat / frontier verbs are never driven) */' \
  'int conscience_check(unsigned char site, const void *q) { (void)site; (void)q; return 0; }' \
  'const char *conscience_on_refuse(unsigned char site, int verdict) { (void)site; (void)verdict; return ""; }' \
  'void frontier_self_test(void (*emit)(const char *)) { (void)emit; }' > "$STUB"
SRC="$SRC $STUB"
CFLAGS="-std=c11 -O1 -Wall -Wextra -ffp-contract=off"
echo "[build] compiling the read-back cert and its falsifier ..."
"$CC" $CFLAGS $SRC -lm -o "$WORK/r" || { echo "[build] FAILED"; exit 1; }
"$CC" $CFLAGS -DST_DMN_RESTORE_DISABLE $SRC -lm -o "$WORK/r_off" || { echo "[build] falsifier FAILED"; exit 1; }
"$CC" $CFLAGS -DST_DMN_REST_DISABLE $SRC -lm -o "$WORK/r_norest" || { echo "[build] rest falsifier FAILED"; exit 1; }
"$CC" $CFLAGS -DST_DMN_REST_ABORT_KEEP $SRC -lm -o "$WORK/r_keep" || { echo "[build] rest-writer falsifier FAILED"; exit 1; }
"$CC" $CFLAGS -DST_DMN_REST_DLB_KEEP $SRC -lm -o "$WORK/r_dlb" || { echo "[build] rest-dlb falsifier FAILED"; exit 1; }
"$CC" $CFLAGS -DDLB_NO_REFUND $SRC -lm -o "$WORK/r_ref" || { echo "[build] refund falsifier FAILED"; exit 1; }
"$CC" $CFLAGS -DDLB_NO_EVICT_KEPT $SRC -lm -o "$WORK/r_evk" || { echo "[build] evict falsifier FAILED"; exit 1; }
"$CC" $CFLAGS -DDLB_REFUND_UNBOUNDED $SRC -lm -o "$WORK/r_unb" || { echo "[build] refund-once falsifier FAILED"; exit 1; }
# all run side by side (each is ~1 min a DMN tick); the falsifiers stop after the rest checks
( cd "$ROOT" && env -u PKERNEL_STUDENT_EMA "$WORK/r_off" back > "$WORK/off.log" 2>&1 ) &
OFF_PID=$!
( cd "$ROOT" && env -u PKERNEL_STUDENT_EMA "$WORK/r_norest" back > "$WORK/norest.log" 2>&1 ) &
NOREST_PID=$!
( cd "$ROOT" && env -u PKERNEL_STUDENT_EMA "$WORK/r_keep" back > "$WORK/keep.log" 2>&1 ) &
KEEP_PID=$!
( cd "$ROOT" && env -u PKERNEL_STUDENT_EMA "$WORK/r_dlb" back > "$WORK/dlb.log" 2>&1 ) &
DLB_PID=$!
( cd "$ROOT" && env -u PKERNEL_STUDENT_EMA "$WORK/r_ref" dlb > "$WORK/ref.log" 2>&1 ) &
REF_PID=$!
( cd "$ROOT" && env -u PKERNEL_STUDENT_EMA "$WORK/r_evk" dlb > "$WORK/evk.log" 2>&1 ) &
EVK_PID=$!
( cd "$ROOT" && env -u PKERNEL_STUDENT_EMA "$WORK/r_unb" dlb > "$WORK/unb.log" 2>&1 ) &
UNB_PID=$!
echo "=== plain (must PASS) ==="
( cd "$ROOT" && env -u PKERNEL_STUDENT_EMA "$WORK/r" ); RC=$?
wait "$OFF_PID"; wait "$NOREST_PID"; wait "$KEEP_PID"; wait "$DLB_PID"; wait "$REF_PID"; wait "$EVK_PID"; wait "$UNB_PID"
echo "=== -DST_DMN_RESTORE_DISABLE back (must FAIL on [restore-back]) ==="
cat "$WORK/off.log"
grep -q 'FAIL  \[restore-back\] live == the saved best' "$WORK/off.log"; NC=$?
echo "=== -DST_DMN_REST_DISABLE back (must FAIL on [restore-rest]) ==="
cat "$WORK/norest.log"
grep -q 'FAIL  \[restore-rest\] same corpus after a read-back' "$WORK/norest.log" || NC=1
echo "=== -DST_DMN_REST_ABORT_KEEP back (must FAIL on [restore-rest] writer) ==="
cat "$WORK/keep.log"
grep -q 'FAIL  \[restore-rest\] a writer ends the rest' "$WORK/keep.log" || NC=1
echo "=== -DST_DMN_REST_DLB_KEEP back (must FAIL on [restore-rest] DLB winner) ==="
cat "$WORK/dlb.log"
grep -q 'FAIL  \[restore-rest\] a waiting DLB winner ends the rest' "$WORK/dlb.log" || NC=1
echo "=== -DDLB_NO_REFUND dlb (must FAIL on [restore-dlb]) ==="
cat "$WORK/ref.log"
grep -q 'FAIL  \[restore-dlb\] the read-back gives the winner its passes back' "$WORK/ref.log" || NC=1
echo "=== -DDLB_NO_EVICT_KEPT dlb (must FAIL on [restore-dlb] full ring) ==="
cat "$WORK/evk.log"
grep -q 'FAIL  \[restore-dlb\] a full ring of passes kept for a refund' "$WORK/evk.log" || NC=1
echo "=== -DDLB_REFUND_UNBOUNDED dlb (must FAIL on [restore-dlb] once) ==="
cat "$WORK/unb.log"
grep -q 'FAIL  \[restore-dlb\] a winner is given its passes back once' "$WORK/unb.log" || NC=1
if [ "$RC" -eq 0 ] && [ "$NC" -eq 0 ]; then echo "[result] PASS  dmn-restore (plain green, falsifier red)"; exit 0; fi
echo "[result] FAIL  dmn-restore (plain rc=$RC, falsifier red on [restore-back]: $([ "$NC" -eq 0 ] && echo yes || echo no))"
exit 1
