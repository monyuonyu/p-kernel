#!/bin/bash
# ---------------------------------------------------------------------------
# run_shellmerge.sh - the shell's `student merge` must not make the live student
# worse (tests/llm/student_shellmerge_test.c, research/brain-merge-e3-log.md).
#
#   ./run_shellmerge.sh      exit 0 = the plain build passes and the falsifier
#                            -DST_SHELL_MERGE_PLAIN (the old verb) turns
#                            [smerge-held] red
#   SMERGE_ROUNDS=<n>        sleep rounds at ST_LR before the merge (default 40)
# ---------------------------------------------------------------------------
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
CC="${CC:-cc}"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
L="$ROOT/arch/common/llm"
SRC="$HERE/student_shellmerge_test.c $L/student.c $L/cradle.c $L/dlb.c $L/held_indep.c"
STUB="$WORK/smerge_stub.c"
printf '%s\n' \
  '/* auto-generated by run_shellmerge.sh: link-only stubs */' \
  'int conscience_check(unsigned char site, const void *q) { (void)site; (void)q; return 0; }' \
  'const char *conscience_on_refuse(unsigned char site, int verdict) { (void)site; (void)verdict; return ""; }' \
  'void frontier_self_test(void (*emit)(const char *)) { (void)emit; }' > "$STUB"
SRC="$SRC $STUB"
CFLAGS="-std=c11 -O1 -Wall -Wextra -ffp-contract=off"
TICKS="${SMERGE_ROUNDS:-40}"
build() { # <out> <flags...>
    local o="$1"; shift
    # shellcheck disable=SC2086
    "$CC" $CFLAGS "$@" $SRC -lm -o "$WORK/$o" || { echo "[build] $o FAILED"; exit 1; }
}
echo "[build] shell merge: plain, -DST_SHELL_MERGE_PLAIN ..."
build sm
build sm_plain -DST_SHELL_MERGE_PLAIN
fail=0
echo "== plain"
"$WORK/sm" "$TICKS" | tee "$WORK/sm.log"
grep -q '^\[result\] PASS' "$WORK/sm.log" || { echo "[shellmerge] FAIL plain"; fail=1; }
echo "== falsifier -DST_SHELL_MERGE_PLAIN (the old verb)"
"$WORK/sm_plain" "$TICKS" | tee "$WORK/sm_plain.log"
if grep -q '^  FAIL  \[smerge-held\]' "$WORK/sm_plain.log"; then
    echo "[shellmerge] falsifier red on [smerge-held] (as it must)"
else
    echo "[shellmerge] FAIL the falsifier did not turn [smerge-held] red"; fail=1
fi
[ "$fail" = 0 ] && echo "[result] PASS  shell merge" || echo "[result] FAIL  shell merge"
exit "$fail"
