#!/bin/bash
# ---------------------------------------------------------------------------
# run_st_nan.sh - a non-finite model must never read as a good one
#                 (tests/llm/student_nan_test.c, ROADMAP B4).
#   plain                    ALL PASS, with PKERNEL_STUDENT_EMA unset and set
#   -DST_LOGF_NO_FINITE      [logf-nonfinite] [loss-not-better] [guarded-nan] RED
#   -DST_SAVE_NO_FINITE      the [gate-*] of a model the loss does not stop RED,
#                            [gate-after-good] stays green (st_logf holds it)
#   both                     [gate-after-good] RED too: that is the bug itself
# exit 0 = plain green, every falsifier red exactly where it should be.
# ---------------------------------------------------------------------------
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
CC="${CC:-cc}"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

SRC="$HERE/student_nan_test.c $ROOT/arch/common/llm/student.c $ROOT/arch/common/llm/cradle.c $ROOT/arch/common/llm/dlb.c"
SRC="$SRC $ROOT/arch/common/llm/held_indep.c"
STUB="$WORK/nan_stub.c"
printf '%s\n' \
  '/* auto-generated by run_st_nan.sh: link-only stubs */' \
  'int conscience_check(unsigned char site, const void *q) { (void)site; (void)q; return 0; }' \
  'const char *conscience_on_refuse(unsigned char site, int verdict) { (void)site; (void)verdict; return ""; }' \
  'void frontier_self_test(void (*emit)(const char *)) { (void)emit; }' > "$STUB"
SRC="$SRC $STUB"
CFLAGS="-std=c11 -O1 -Wall -Wextra -ffp-contract=off"

build() { # <out> <flags...>
    local o="$1"; shift
    # shellcheck disable=SC2086
    "$CC" $CFLAGS "$@" $SRC -lm -o "$WORK/$o" || { echo "[build] $o FAILED"; exit 1; }
}
echo "[build] plain and three falsifiers ..."
build plain
build nologf -DST_LOGF_NO_FINITE
build nosave -DST_SAVE_NO_FINITE
build both   -DST_LOGF_NO_FINITE -DST_SAVE_NO_FINITE

FAILS=0
want() { # <label> <log> <PASS|FAIL> <check>
    if grep -qF "  $3  $4" "$2"; then
        echo "  ok    $1: $4 is $3"
    else
        echo "  WRONG $1: $4 should be $3"; FAILS=$((FAILS + 1))
    fi
}
arm() { # <binary> <args> -> runs from ROOT, log in $WORK/<binary><args>.log
    local b="$1"; shift
    local l="$WORK/$b$*.log"
    ( cd "$ROOT" && "$WORK/$b" "$@" ) > "$l" 2>&1
    echo "$?" > "$l.rc"
    grep -E '^(  (PASS|FAIL)|    |\[result\])' "$l"
}

echo ""; echo "=== plain (must PASS) ==="
arm plain
[ "$(cat "$WORK/plain.log.rc")" = 0 ] || { echo "  WRONG plain rc"; FAILS=$((FAILS + 1)); }
echo ""; echo "=== plain, the saved copy (must PASS) ==="
PKERNEL_STUDENT_EMA=1 arm plain ema
[ "$(cat "$WORK/plainema.log.rc")" = 0 ] || { echo "  WRONG plain ema rc"; FAILS=$((FAILS + 1)); }

echo ""; echo "=== -DST_LOGF_NO_FINITE ==="
arm nologf > /dev/null
L="$WORK/nologf.log"
want nologf "$L" FAIL "[logf-nonfinite]"
want nologf "$L" PASS "[logf-finite-bits]"
want nologf "$L" FAIL "[loss-not-better]"
want nologf "$L" FAIL "[guarded-nan]"
want nologf "$L" PASS "[gate-first]"
want nologf "$L" PASS "[gate-after-good]"
want nologf "$L" PASS "[gate-clean]"

echo ""; echo "=== -DST_SAVE_NO_FINITE ==="
arm nosave > /dev/null
L="$WORK/nosave.log"
want nosave "$L" PASS "[logf-nonfinite]"
want nosave "$L" PASS "[loss-not-better]"
want nosave "$L" PASS "[gate-clean]"
want nosave "$L" PASS "[gate-persist-clean]"
want nosave "$L" PASS "[gate-after-good]"
want nosave "$L" FAIL "[gate-first]"
want nosave "$L" FAIL "[gate-unused-nan]"
want nosave "$L" FAIL "[gate-unused-inf]"
want nosave "$L" FAIL "[gate-adam]"
want nosave "$L" FAIL "[gate-persist]"
PKERNEL_STUDENT_EMA=1 arm nosave ema > /dev/null
L="$WORK/nosaveema.log"
want nosave-ema "$L" PASS "[gate-ema-wins]"
want nosave-ema "$L" FAIL "[gate-ema]"

echo ""; echo "=== both ==="
arm both > /dev/null
L="$WORK/both.log"
want both "$L" FAIL "[gate-after-good]"
want both "$L" PASS "[gate-clean]"

echo ""
if [ "$FAILS" -eq 0 ]; then
    echo "[result] PASS  a non-finite model does not read as good; plain green, falsifiers red where they should be"
    exit 0
fi
echo "[result] FAIL  $FAILS wrong"
exit 1
